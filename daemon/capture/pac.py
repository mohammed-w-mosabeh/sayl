"""The proxy auto-config (PAC) file the system proxy points at. Pure functions, plus its secret.

Browsers fetch it from sayld at `/capture/pac/<secret>.pac`. The route needs no bearer token,
because browsers cannot send one, so the path carries a random secret instead: other local users
cannot read which hosts are on the passthrough list.

The script fails open. Loopback and passthrough hosts go DIRECT, everything else goes to
sayl-capture with DIRECT as the fallback, so a stopped or crashed sayl-capture never breaks
browsing. If sayld itself is down, browsers cannot fetch the file and go DIRECT as well.
"""

import json
import os
import secrets
from collections.abc import Iterable
from pathlib import Path

SECRET_FILE = "pac-secret"  # noqa: S105 - a file name, not a secret


def secret(state_dir: Path) -> str:
    """The random path segment, created once with mode 0600."""
    file = state_dir / SECRET_FILE
    state_dir.mkdir(parents=True, exist_ok=True, mode=0o700)
    try:
        descriptor = os.open(file, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    except FileExistsError:
        file.chmod(0o600)
        return file.read_text().strip()
    value = secrets.token_urlsafe(24)
    with os.fdopen(descriptor, "w") as stream:
        stream.write(value)
    return value


def url(daemon_port: int, value: str) -> str:
    return f"http://127.0.0.1:{daemon_port}/capture/pac/{value}.pac"


def script(capture_port: int, bypass: Iterable[str]) -> str:
    """FindProxyForURL for these passthrough entries. Path entries need decryption: skipped."""
    hosts: list[str] = []
    globs: list[str] = []
    for entry in bypass:
        value = entry.strip().lower()
        if not value or "/" in value:
            continue
        (globs if any(char in value for char in "*?[") else hosts).append(value)
    return f"""// Generated by Sayl. Edit the passthrough list in Sayl, not this file.
var HOSTS = {json.dumps(sorted(set(hosts)))};
var GLOBS = {json.dumps(sorted(set(globs)))};
function FindProxyForURL(url, host) {{
  host = host.toLowerCase();
  if (isPlainHostName(host) || host === "localhost" || host === "::1" || host === "[::1]" ||
      shExpMatch(host, "127.*") || shExpMatch(host, "*.localhost")) {{
    return "DIRECT";
  }}
  for (var i = 0; i < HOSTS.length; i++) {{
    if (host === HOSTS[i] || dnsDomainIs(host, "." + HOSTS[i])) {{
      return "DIRECT";
    }}
  }}
  for (var j = 0; j < GLOBS.length; j++) {{
    if (shExpMatch(host, GLOBS[j])) {{
      return "DIRECT";
    }}
  }}
  return "PROXY 127.0.0.1:{capture_port}; DIRECT";
}}
"""
